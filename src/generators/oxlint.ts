interface RuleSelection {
  enabled: readonly string[];
  disabled: readonly string[];
}

const RULE_SELECTION = { enabled: ENABLED_RULES, disabled: DISABLED_RULES };

function duplicates(names: readonly string[]) {
  const seen = new Set<string>();

  return names.filter((name) => {
    const isDuplicate = seen.has(name);

    seen.add(name);

    return isDuplicate;
  });
}

function reportRuleErrors(issues: Record<string, readonly string[]>) {
  const messages = Object.entries(issues)
    .filter(([, names]) => names.length > 0)
    .map(([label, names]) => `${label}:\n${names.map((name) => `  ${name}`).join("\n")}`);

  if (messages.length > 0) {
    throw new Error(`Oxlint rule catalog validation failed.\n${messages.join("\n")}`);
  }
}

function validateRuleCatalog(
  available: readonly string[],
  selection: RuleSelection = RULE_SELECTION,
) {
  const declared = [...selection.enabled, ...selection.disabled];
  const availableNames = new Set(available);
  const declaredNames = new Set(declared);
  const disabledNames = new Set(selection.disabled);

  reportRuleErrors({
    "Duplicate catalog rules": duplicates(available),
    "Duplicate enabled rules": duplicates(selection.enabled),
    "Duplicate disabled rules": duplicates(selection.disabled),
    "Rules both enabled and disabled": selection.enabled.filter((name) => disabledNames.has(name)),
    "Unclassified rules": available.filter((name) => !declaredNames.has(name)),
    "Removed or renamed rules": declared.filter((name) => !availableNames.has(name)),
  });
}

function validateRuleReferences(available: readonly string[], configured: readonly string[]) {
  const availableNames = new Set(available);

  reportRuleErrors({
    "Unknown configured rules": [...new Set(configured)].filter(
      (name) => !availableNames.has(name),
    ),
  });
}

